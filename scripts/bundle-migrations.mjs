// Every migration, in order, as one paste.
//
// Standing up a fresh Supabase project means applying 0001 onward. Pasting
// thirteen files by hand into the SQL editor is exactly the kind of tedium that
// produces a half-applied schema, and a half-applied schema is worse than none:
// the suites fail in ways that look like product bugs.
//
//   node scripts/bundle-migrations.mjs > /tmp/porchlight-schema.sql
//
// Deliberately NOT for the production project. The migrations are forward-only
// and not idempotent, so re-running 0001 against a database that already has it
// is destructive. This exists for a brand-new, empty project and nothing else,
// which is why it refuses to write into the repo and prints to stdout.
import fs from "node:fs";
import path from "node:path";

const DIR = "supabase/migrations";

const files = fs
  .readdirSync(DIR)
  .filter((f) => /^\d{4}_.*\.sql$/.test(f))
  .sort();

if (!files.length) {
  console.error(`No migrations found in ${DIR}/`);
  process.exit(1);
}

// A gap means a migration is missing from the working tree, and applying the
// rest would build a schema that never existed. Refuse rather than produce a
// bundle that looks complete.
const numbers = files.map((f) => Number(f.slice(0, 4)));
const missing = [];
for (let n = 1; n <= numbers[numbers.length - 1]; n++) {
  if (!numbers.includes(n)) missing.push(String(n).padStart(4, "0"));
}
if (missing.length) {
  console.error(`Missing migration(s): ${missing.join(", ")}. Refusing to bundle.`);
  process.exit(1);
}

const out = [];
out.push("-- Porchlight schema: migrations " + files[0].slice(0, 4) + "-" +
  files[files.length - 1].slice(0, 4) + ", concatenated in order.");
out.push("--");
out.push("-- Generated by scripts/bundle-migrations.mjs. FOR AN EMPTY PROJECT ONLY.");
out.push("-- These are forward-only and not idempotent; running this against a");
out.push("-- database that already has the schema will destroy data.");
out.push("");
out.push("begin;");
out.push("");

for (const f of files) {
  out.push(`-- ${"=".repeat(72)}`);
  out.push(`-- ${f}`);
  out.push(`-- ${"=".repeat(72)}`);
  out.push(fs.readFileSync(path.join(DIR, f), "utf8").trimEnd());
  out.push("");
}

// One transaction, so a failure anywhere leaves an empty project rather than a
// partial schema that has to be diagnosed before it can be dropped.
out.push("commit;");
out.push("");

console.log(out.join("\n"));
console.error(`Bundled ${files.length} migrations (${files[0]} … ${files[files.length - 1]}).`);
